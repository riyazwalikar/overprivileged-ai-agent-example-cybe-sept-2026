#!/usr/bin/env bash
# Generate .env from .env.example with a real local token and fresh decoys.
# Idempotent: skips if .env exists unless FORCE=1.
set -euo pipefail
cd "$(dirname "$0")/.."

if [ -f .env ] && [ "${FORCE:-0}" != "1" ]; then
    echo ".env already exists (set FORCE=1 to regenerate)"
    exit 0
fi

TOKEN="$(openssl rand -hex 24)"
STRIPE="sk_live_$(openssl rand -hex 12)"
SENTRY_KEY="$(openssl rand -hex 16)"
BASIC_AUTH_PW="$(openssl rand -hex 12)"

sed -e "s|^INTERNAL_OPS_TOKEN=.*|INTERNAL_OPS_TOKEN=${TOKEN}|" \
    -e "s|^STRIPE_API_KEY=.*|STRIPE_API_KEY=${STRIPE}|" \
    -e "s|^SENTRY_DSN=.*|SENTRY_DSN=https://${SENTRY_KEY}@o0.ingest.example.com/0|" \
    .env.example > .env

chmod 600 .env

mkdir -p secrets
printf '%s' "${BASIC_AUTH_PW}" > secrets/basic_auth_password
chmod 600 secrets/basic_auth_password

cat > creds.md <<EOF
# Demo access credentials — generated by scripts/gen_env.sh
# HTTP Basic auth for the support-agent
username: comet
password: ${BASIC_AUTH_PW}
EOF
chmod 600 creds.md

echo "Wrote .env and creds.md (fresh INTERNAL_OPS_TOKEN, decoys, basic-auth password)"
